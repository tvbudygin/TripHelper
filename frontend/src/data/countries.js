/** Приводит название к виду для сравнения */
export function normalizeCountryName(name) {
  return String(name)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[’`]/g, "'")
    .replace(/\./g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

