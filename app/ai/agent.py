"""Агент: отвечает на вопрос пользователя по данным его поездки"""

from app.ai.client import ask_model, looks_like_real_reply

AGENT_SYSTEM_PROMPT = """Ты — помощник сервиса TripHelper. Отвечай кратко, по-русски и по делу.

Есть два вида вопросов:
1. Вопрос о поездке пользователя (рейсы, жильё, даты, активности) — отвечай только по данным
   ниже и по истории диалога. Если нужных данных там нет — так и скажи.
2. Просьба о совете (где поесть, что посмотреть, куда сходить, что попробовать) — здесь данные
   поездки нужны только чтобы понять город и страну, а сам совет давай из своих общих знаний
   о месте. Назови 3–5 конкретных известных мест, районов или блюд и в одной фразе поясни, чем
   они хороши. Если пользователь назвал другой город (в вопросе или раньше в диалоге) — советуй
   про него. Не отвечай «в данных нет информации» на просьбу о совете.

Называй только те места и блюда, в существовании которых уверен; если не уверен — лучше назови
   районы и типичные блюда кухни, чем выдумывай названия заведений.

Не выдумывай точные цены, часы работы и телефоны — для них пиши «уточните перед визитом»."""

MAX_ATTEMPTS = 2


def generate_answer(question: str, trip_context: str, history: list[dict]) -> str | None:
    """Формирует ответ на вопрос. Возвращает None, если модель не ответила"""

    messages = [{"role": "system", "content": f"{AGENT_SYSTEM_PROMPT}\n\nДанные о поездке:\n{trip_context}"}]
    messages.extend(history)
    messages.append({"role": "user", "content": question})

    for _ in range(MAX_ATTEMPTS):
        reply = ask_model(messages)
        if reply and looks_like_real_reply(reply):
            return reply
    return None
