"""Валидатор: проверяет ответ агента перед показом пользователю"""

from app.ai.client import ask_model, looks_like_real_reply

VALIDATOR_PROMPT = """Ты проверяешь ответ помощника перед отправкой пользователю.
Тебе дали данные о поездке и черновик ответа.
- Общеизвестные достопримечательности, районы, блюда и известные заведения города оставляй как есть —
  это нормальные рекомендации, их не нужно убирать и не нужно писать, что «данных нет».
- Если в ответе есть точные цены, часы работы или телефоны — замени их на «уточните перед визитом».
- Если ответ противоречит данным о поездке — исправь его по данным.
Если всё в порядке — верни ответ как есть, без изменений и без пояснений о своей проверке."""


def validate_answer(question: str, trip_context: str, draft_answer: str) -> str:
    """Возвращает проверенный ответ (или черновик, если проверка не сработала)"""

    checked = ask_model([
        {"role": "system", "content": VALIDATOR_PROMPT},
        {
            "role": "user",
            "content": (
                f"Данные о поездке:\n{trip_context}\n\n"
                f"Вопрос: {question}\n\n"
                f"Черновик ответа:\n{draft_answer}"
            ),
        },
    ])
    return checked if checked and looks_like_real_reply(checked) else draft_answer
